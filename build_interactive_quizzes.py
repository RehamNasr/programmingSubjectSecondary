def build_quiz_html(lesson_id, quiz):
    html = f'''
    <!-- Interactive Quiz & Assessment Card for {lesson_id} -->
    <div class="lesson-quiz-wrap" id="quiz-wrap-{lesson_id}">
      <div class="quiz-header">
        <div class="quiz-title-box">
          <h3>📝 بنك الأسئلة والتقييمات التفاعلية — {quiz['title']}</h3>
          <p>اختبر معلوماتك فورًا مع التغذية الراجعة التلقائية (بنك أسئلة سيمي كولون + تقييمات الوزارة الأسبوعية)</p>
        </div>
        <div class="quiz-header-actions">
          <div class="quiz-score-badge" id="score-{lesson_id}">🎯 النتيجة: 0 / {len([q for q in quiz['questions'] if q['type'] in ['mcq', 'tf']])}</div>
          <button type="button" class="quiz-reset-btn" onclick="resetQuiz('{lesson_id}')">🔄 إعادة الاختبار</button>
        </div>
      </div>

      <div class="quiz-filters">
        <button type="button" class="quiz-filter-btn active" onclick="filterQuiz('{lesson_id}', 'all', this)">⭐ جميع الأسئلة ({len(quiz['questions'])})</button>
        <button type="button" class="quiz-filter-btn" onclick="filterQuiz('{lesson_id}', 'mcq', this)">🔘 اختيار من متعدد</button>
        <button type="button" class="quiz-filter-btn" onclick="filterQuiz('{lesson_id}', 'tf', this)">✔️ صح أو خطأ</button>
        <button type="button" class="quiz-filter-btn" onclick="filterQuiz('{lesson_id}', 'term', this)">🏷️ مصطلحات وأكمل</button>
        <button type="button" class="quiz-filter-btn" onclick="filterQuiz('{lesson_id}', 'ministry', this)">📋 تقييمات الوزارة والواجبات</button>
      </div>

      <div class="quiz-questions-list" id="qlist-{lesson_id}">
    '''

    for idx, q in enumerate(quiz['questions']):
        q_num = idx + 1
        q_type = q['type']
        
        if q_type == 'mcq':
            badge_html = '<span class="q-badge mcq">اختيار من متعدد</span>'
            html += f'''
        <div class="q-card" data-type="mcq" id="q-{lesson_id}-{q_num}">
          <div class="q-head">
            {badge_html}
            <div class="q-text"><b>س{q_num}:</b> {q['text']}</div>
          </div>
          <div class="q-options">
            '''
            for opt_idx, opt in enumerate(q['options']):
                is_correct = "true" if opt['c'] else "false"
                opt_text = opt['t'].replace('"', '&quot;')
                exp_text = q['exp'].replace('"', '&quot;')
                html += f'''<button type="button" class="quiz-btn" data-correct="{is_correct}" onclick="checkOption(this, '{lesson_id}', '{q_num}', '{exp_text}')"><span>{opt['t']}</span> <span class="opt-icon"></span></button>'''
            html += f'''
          </div>
          <div class="q-feedback" id="feedback-{lesson_id}-{q_num}"></div>
        </div>
            '''

        elif q_type == 'tf':
            badge_html = '<span class="q-badge tf">صح أو خطأ</span>'
            exp_text = q['exp'].replace('"', '&quot;')
            c_true = "true" if q['correct'] else "false"
            c_false = "false" if q['correct'] else "true"
            html += f'''
        <div class="q-card" data-type="tf" id="q-{lesson_id}-{q_num}">
          <div class="q-head">
            {badge_html}
            <div class="q-text"><b>س{q_num}:</b> {q['text']}</div>
          </div>
          <div class="q-options" style="grid-template-columns: 1fr 1fr; max-width: 480px;">
            <button type="button" class="quiz-btn" data-correct="{c_true}" onclick="checkOption(this, '{lesson_id}', '{q_num}', '{exp_text}')"><span>✔️ عبارة صحيحة</span> <span class="opt-icon"></span></button>
            <button type="button" class="quiz-btn" data-correct="{c_false}" onclick="checkOption(this, '{lesson_id}', '{q_num}', '{exp_text}')"><span>❌ عبارة خاطئة</span> <span class="opt-icon"></span></button>
          </div>
          <div class="q-feedback" id="feedback-{lesson_id}-{q_num}"></div>
        </div>
            '''

        elif q_type == 'term':
            badge_html = '<span class="q-badge term">المصطلح العلمي / أكمل</span>'
            ans_clean = q['ans'].replace('"', '&quot;')
            html += f'''
        <div class="q-card" data-type="term" id="q-{lesson_id}-{q_num}">
          <div class="q-head">
            {badge_html}
            <div class="q-text"><b>س{q_num} (اكتب المصطلح):</b> {q['text']}</div>
          </div>
          <div>
            <button type="button" class="written-ans-toggle" onclick="toggleWrittenAns(this)">🔍 اضغط لإظهار الإجابة النموذجية</button>
            <div class="written-ans-box"><b>الإجابة النموذجية:</b> {q['ans']}</div>
          </div>
        </div>
            '''

        elif q_type == 'ministry':
            badge_html = '<span class="q-badge ministry">تقييم الوزارة الأسبوعي</span>'
            html += f'''
        <div class="q-card" data-type="ministry" id="q-{lesson_id}-{q_num}">
          <div class="q-head">
            {badge_html}
            <div class="q-text"><b>س{q_num} (سؤال مقالي):</b> {q['text']}</div>
          </div>
          <div>
            <button type="button" class="written-ans-toggle" onclick="toggleWrittenAns(this)">📋 اعرض نموذج الإجابة وتوزيع الدرجات</button>
            <div class="written-ans-box">{q['ans']}</div>
          </div>
        </div>
            '''

    html += '''
      </div>
    </div>
    '''
    return html
